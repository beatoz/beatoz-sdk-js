/**
 * Runs the node the integration tests talk to, and writes the `.env` they read.
 *
 *   node scripts/testnode.mjs start   pull, run, wait, write .env
 *   node scripts/testnode.mjs stop    remove the container
 *   node scripts/testnode.mjs env     rewrite .env from a running container
 *
 * The image initialises a fresh chain on first start and prints ten funded
 * wallet keys, so the keys change every time the container is recreated. That
 * is why `.env` is generated rather than kept: there is nothing stable to keep.
 * It is gitignored, and the image itself says these keys are for testing only.
 *
 * Adding `reward` to any command runs a second node for the reward tests
 * instead, and writes `.env.reward`:
 *
 *   node scripts/testnode.mjs start reward
 *
 * It is the same image with one governance value changed. The chain pays
 * inflation rewards once per inflationCycleBlocks, a week of blocks by default,
 * so a test that withdraws a reward cannot run against the regular node. This
 * one starts from a genesis the image's own `beatoz init` writes, with that
 * value lowered and nothing else touched.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const config = JSON.parse(fs.readFileSync(path.join(here, 'testnode.config.json'), 'utf8'));

// Pinned by digest, not by tag. The digest names the multi-arch index, so each
// machine still pulls its own architecture - but a tag can be moved to point at
// different contents, and then developers and CI would not be on the same node.
const imageRef = `${config.image}@${config.digest}`;

// The image's entrypoint initialises a chain with this id when it finds no
// genesis, so the reward node uses the same one.
const CHAIN_ID = '0x1234';
const WEEK_SECONDS = 7 * 24 * 60 * 60;

const docker = (args, opts = {}) =>
    execFileSync('docker', args, { encoding: 'utf8', stdio: 'pipe', ...opts });

const dockerQuiet = (args) => {
    try {
        return docker(args);
    } catch {
        return '';
    }
};

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const rpcUrlOf = (node) => `http://localhost:${node.rpcPort}`;

async function waitForRpc(node, timeoutMs = 60000) {
    const rpcUrl = rpcUrlOf(node);
    const deadline = Date.now() + timeoutMs;
    for (;;) {
        try {
            const response = await fetch(`${rpcUrl}/status`, { signal: AbortSignal.timeout(2000) });
            if (response.ok) {
                return (await response.json()).result;
            }
        } catch {
            // not up yet
        }
        if (Date.now() > deadline) {
            throw new Error(`the node did not answer on ${rpcUrl} within ${timeoutMs}ms`);
        }
        await sleep(500);
    }
}

/**
 * Reads the funded wallet keys from the running container.
 *
 * The entrypoint prints them on startup as `address : 0x...` / `private key :
 * 0x...` pairs, under a banner saying not to use them anywhere but a test.
 * This runs the same command it runs rather than reading its logs: the logs
 * grow with every block, and once past execFileSync's 1 MB buffer they could
 * no longer be read at all.
 */
function readWallets(node) {
    const printKeys =
        'for file in /root/.beatoz/walkeys/wk*.json; do ' +
        `beatoz wallet-key "$file" | grep -v 'wallet file' | ` +
        `awk -F': ' '{print $1 ": 0x" tolower($2)}'; done`;
    const logs = docker(['exec', node.container, 'sh', '-c', printKeys]);
    const wallets = [];
    let address;
    for (const line of logs.split('\n')) {
        const addr = line.match(/^address\s*:\s*(0x[0-9a-fA-F]{40})/);
        if (addr) {
            address = addr[1];
            continue;
        }
        const key = line.match(/^private key\s*:\s*(0x[0-9a-fA-F]{64})/);
        if (key && address) {
            wallets.push({ address, privateKey: key[1] });
            address = undefined;
        }
    }
    return wallets;
}

const envHeader = (command) => [
    `# Generated by scripts/testnode.mjs from ${config.image}:${config.tag}`,
    `# (${config.digest})`,
    '#',
    '# These keys come from that image, which prints them on startup and says',
    '# not to use them anywhere but a test. They are regenerated whenever the',
    '# container initialises a fresh chain, so this file is disposable and',
    `# gitignored - run \`${command}\` again rather than editing it.`,
    '',
];

function writeEnv(chainId, wallets) {
    if (wallets.length < 2) {
        throw new Error(
            `the container printed ${wallets.length} wallet keys; the tests need two distinct accounts`,
        );
    }
    const [first, second] = wallets;
    const envPath = path.join(repoRoot, '.env');
    fs.writeFileSync(
        envPath,
        [
            ...envHeader('yarn node:start'),
            `BEATOZ_RPC_URL=${rpcUrlOf(config)}`,
            `BEATOZ_WS_URL=ws://localhost:${config.rpcPort}/websocket`,
            `BEATOZ_CHAIN_ID=${chainId}`,
            `BEATOZ_TEST_ADDRESS=${first.address}`,
            `BEATOZ_TEST_PRIVATE_KEY=${first.privateKey}`,
            `BEATOZ_TEST_PROPOSAL_ADDRESS=${second.address}`,
            `BEATOZ_TEST_PROPOSAL_PRIVATE_KEY=${second.privateKey}`,
            '',
        ].join('\n'),
        'utf8',
    );
    return { envPath, count: wallets.length };
}

// A separate file, so starting either node never erases the other's settings.
function writeRewardEnv(chainId, wallets) {
    if (wallets.length < 1) {
        throw new Error('the reward node printed no wallet keys');
    }
    const [first] = wallets;
    const node = config.reward;
    const envPath = path.join(repoRoot, '.env.reward');
    fs.writeFileSync(
        envPath,
        [
            ...envHeader('yarn node:start:reward'),
            `# The node pays inflation rewards every ${node.inflationCycleBlocks} blocks.`,
            '',
            `BEATOZ_REWARD_RPC_URL=${rpcUrlOf(node)}`,
            `BEATOZ_REWARD_WS_URL=ws://localhost:${node.rpcPort}/websocket`,
            `BEATOZ_REWARD_CHAIN_ID=${chainId}`,
            `BEATOZ_REWARD_ADDRESS=${first.address}`,
            `BEATOZ_REWARD_PRIVATE_KEY=${first.privateKey}`,
            '',
        ].join('\n'),
        'utf8',
    );
    return { envPath, count: wallets.length };
}

async function start() {
    process.stdout.write(`pulling ${imageRef}\n`);
    docker(['pull', imageRef], { stdio: 'inherit' });

    dockerQuiet(['rm', '-f', config.container]);
    docker([
        'run',
        '-d',
        '--name',
        config.container,
        '-p',
        `${config.rpcPort}:26657`,
        '-p',
        `${config.p2pPort}:26656`,
        imageRef,
    ]);
    process.stdout.write(`started ${config.container}\n`);

    const status = await waitForRpc(config);
    const chainId = status.node_info.network;
    process.stdout.write(
        `node is up: chain ${chainId}, height ${status.sync_info.latest_block_height}\n`,
    );

    await env(chainId);
}

/**
 * Writes the reward node's genesis: the one `beatoz init` produces, with
 * inflationCycleBlocks lowered and every other value left as the image set it.
 *
 * `beatoz init` derives that value as a week of blocks at the configured block
 * interval. It is checked before the change, so if a newer image computes it
 * differently this stops rather than quietly running a different chain.
 */
function patchGenesis(node) {
    const genesisPath = '/root/.beatoz/config/genesis.json';
    const local = path.join(
        fs.mkdtempSync(path.join(os.tmpdir(), 'beatoz-genesis-')),
        'genesis.json',
    );
    try {
        docker(['cp', `${node.container}:${genesisPath}`, local]);
        const genesis = JSON.parse(fs.readFileSync(local, 'utf8'));
        const gov = genesis.app_state.govParams;
        const expected = String(WEEK_SECONDS / node.emptyBlockIntervalSecs);
        if (gov.inflationCycleBlocks !== expected) {
            throw new Error(
                `beatoz init wrote inflationCycleBlocks ${gov.inflationCycleBlocks}, expected ` +
                    `${expected} (a week of ${node.emptyBlockIntervalSecs}s blocks); ` +
                    'check what the image changed before lowering it',
            );
        }
        gov.inflationCycleBlocks = node.inflationCycleBlocks;
        fs.writeFileSync(local, JSON.stringify(genesis, null, 2));
        docker(['cp', local, `${node.container}:${genesisPath}`]);
    } finally {
        fs.rmSync(path.dirname(local), { recursive: true, force: true });
    }
}

async function startReward() {
    const node = config.reward;
    process.stdout.write(`pulling ${imageRef}\n`);
    docker(['pull', imageRef], { stdio: 'inherit' });

    stopReward();
    docker(['volume', 'create', node.volume]);
    const home = `${node.volume}:/root/.beatoz`;

    // The image's own init, so the genesis is what that image would write.
    docker([
        'run',
        '--rm',
        '-v',
        home,
        '--entrypoint',
        'beatoz',
        imageRef,
        'init',
        '--chain_id',
        CHAIN_ID,
        '--home',
        '/root/.beatoz',
        '--consensus.create_empty_blocks_interval',
        `${node.emptyBlockIntervalSecs}s`,
    ]);

    // Created but not started, so the genesis can be changed before the chain
    // reads it. The entrypoint skips its own init when it finds one.
    docker([
        'create',
        '--name',
        node.container,
        '-p',
        `${node.rpcPort}:26657`,
        '-p',
        `${node.p2pPort}:26656`,
        '-v',
        home,
        imageRef,
    ]);
    patchGenesis(node);
    docker(['start', node.container]);
    process.stdout.write(`started ${node.container}\n`);

    const status = await waitForRpc(node);
    const chainId = status.node_info.network;

    // Governance queries fail until the first block is committed.
    let rule;
    for (const deadline = Date.now() + 30000; ;) {
        try {
            const response = await fetch(`${rpcUrlOf(node)}/rule`).then((r) => r.json());
            rule = response.result?.value;
        } catch {
            // not answering yet
        }
        if (rule) break;
        if (Date.now() > deadline) throw new Error('the reward node never answered rule');
        await sleep(500);
    }
    if (rule.inflationCycleBlocks !== node.inflationCycleBlocks) {
        throw new Error(
            `the reward node reports inflationCycleBlocks ${rule.inflationCycleBlocks}, ` +
                `not ${node.inflationCycleBlocks}`,
        );
    }
    process.stdout.write(
        `node is up: chain ${chainId}, rewards every ${rule.inflationCycleBlocks} blocks\n`,
    );

    await envReward(chainId);
}

async function env(knownChainId) {
    const chainId = knownChainId ?? (await waitForRpc(config, 10000)).node_info.network;
    const { envPath, count } = writeEnv(chainId, readWallets(config));
    process.stdout.write(
        `wrote ${path.relative(repoRoot, envPath)} using 2 of the ${count} funded accounts\n`,
    );
}

async function envReward(knownChainId) {
    const node = config.reward;
    const chainId = knownChainId ?? (await waitForRpc(node, 10000)).node_info.network;
    const { envPath, count } = writeRewardEnv(chainId, readWallets(node));
    process.stdout.write(
        `wrote ${path.relative(repoRoot, envPath)} using 1 of the ${count} funded accounts\n`,
    );
}

function stop() {
    const removed = dockerQuiet(['rm', '-f', config.container]).trim();
    process.stdout.write(
        removed ? `removed ${config.container}\n` : `${config.container} was not running\n`,
    );
}

function stopReward() {
    const node = config.reward;
    const removed = dockerQuiet(['rm', '-f', node.container]).trim();
    dockerQuiet(['volume', 'rm', '-f', node.volume]);
    process.stdout.write(
        removed ? `removed ${node.container}\n` : `${node.container} was not running\n`,
    );
}

const [command, profile] = process.argv.slice(2);
const commands =
    profile === 'reward'
        ? { start: startReward, stop: stopReward, env: () => envReward() }
        : profile === undefined
          ? { start, stop, env: () => env() }
          : {};
try {
    if (!commands[command]) {
        process.stderr.write('usage: node scripts/testnode.mjs start|stop|env [reward]\n');
        process.exit(2);
    }
    await commands[command]();
} catch (err) {
    process.stderr.write(`${err.message}\n`);
    process.exit(1);
}
