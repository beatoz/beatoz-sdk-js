/**
 * Runs the node the integration tests talk to, and writes the `.env` they read.
 *
 *   node scripts/testnode.mjs start   pull, run, wait, write .env
 *   node scripts/testnode.mjs stop    remove the container
 *   node scripts/testnode.mjs env     rewrite .env from a running container
 *
 * The image initialises a fresh chain on first start and prints ten funded
 * wallet keys, so the keys change every time the container is recreated. That
 * is why `.env` is generated rather than kept: there is nothing stable to keep.
 * It is gitignored, and the image itself says these keys are for testing only.
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const config = JSON.parse(fs.readFileSync(path.join(here, 'testnode.config.json'), 'utf8'));

// Pinned by digest, not by tag. The digest names the multi-arch index, so each
// machine still pulls its own architecture - but a tag can be moved to point at
// different contents, and then developers and CI would not be on the same node.
const imageRef = `${config.image}@${config.digest}`;

const docker = (args, opts = {}) =>
    execFileSync('docker', args, { encoding: 'utf8', stdio: 'pipe', ...opts });

const dockerQuiet = (args) => {
    try {
        return docker(args);
    } catch {
        return '';
    }
};

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const rpcUrl = `http://localhost:${config.rpcPort}`;

async function waitForRpc(timeoutMs = 60000) {
    const deadline = Date.now() + timeoutMs;
    for (;;) {
        try {
            const response = await fetch(`${rpcUrl}/status`, { signal: AbortSignal.timeout(2000) });
            if (response.ok) {
                return (await response.json()).result;
            }
        } catch {
            // not up yet
        }
        if (Date.now() > deadline) {
            throw new Error(`the node did not answer on ${rpcUrl} within ${timeoutMs}ms`);
        }
        await sleep(500);
    }
}

/**
 * Reads the wallet keys the entrypoint printed.
 *
 * They only appear in the container's logs, so this is the only place they can
 * come from. The entrypoint prints them as `address : 0x...` / `private key :
 * 0x...` pairs under a banner saying not to use them anywhere but a test.
 */
function readWallets() {
    const logs = dockerQuiet(['logs', config.container]);
    const wallets = [];
    let address;
    for (const line of logs.split('\n')) {
        const addr = line.match(/^address\s*:\s*(0x[0-9a-fA-F]{40})/);
        if (addr) {
            address = addr[1];
            continue;
        }
        const key = line.match(/^private key\s*:\s*(0x[0-9a-fA-F]{64})/);
        if (key && address) {
            wallets.push({ address, privateKey: key[1] });
            address = undefined;
        }
    }
    return wallets;
}

function writeEnv(chainId, wallets) {
    if (wallets.length < 2) {
        throw new Error(
            `the container printed ${wallets.length} wallet keys; the tests need two distinct accounts`,
        );
    }
    const [first, second] = wallets;
    const envPath = path.join(repoRoot, '.env');
    fs.writeFileSync(
        envPath,
        [
            `# Generated by scripts/testnode.mjs from ${config.image}:${config.tag}`,
            `# (${config.digest})`,
            '#',
            '# These keys come from that image, which prints them on startup and says',
            '# not to use them anywhere but a test. They are regenerated whenever the',
            '# container initialises a fresh chain, so this file is disposable and',
            '# gitignored - run `yarn node:start` again rather than editing it.',
            '',
            `BEATOZ_RPC_URL=${rpcUrl}`,
            `BEATOZ_WS_URL=ws://localhost:${config.rpcPort}/websocket`,
            `BEATOZ_CHAIN_ID=${chainId}`,
            `BEATOZ_TEST_ADDRESS=${first.address}`,
            `BEATOZ_TEST_PRIVATE_KEY=${first.privateKey}`,
            `BEATOZ_TEST_PROPOSAL_ADDRESS=${second.address}`,
            `BEATOZ_TEST_PROPOSAL_PRIVATE_KEY=${second.privateKey}`,
            '',
        ].join('\n'),
        'utf8',
    );
    return { envPath, count: wallets.length };
}

async function start() {
    process.stdout.write(`pulling ${imageRef}\n`);
    docker(['pull', imageRef], { stdio: 'inherit' });

    dockerQuiet(['rm', '-f', config.container]);
    docker([
        'run',
        '-d',
        '--name',
        config.container,
        '-p',
        `${config.rpcPort}:26657`,
        '-p',
        `${config.p2pPort}:26656`,
        imageRef,
    ]);
    process.stdout.write(`started ${config.container}\n`);

    const status = await waitForRpc();
    const chainId = status.node_info.network;
    process.stdout.write(
        `node is up: chain ${chainId}, height ${status.sync_info.latest_block_height}\n`,
    );

    await env(chainId);
}

async function env(knownChainId) {
    const chainId = knownChainId ?? (await waitForRpc(10000)).node_info.network;
    const { envPath, count } = writeEnv(chainId, readWallets());
    process.stdout.write(
        `wrote ${path.relative(repoRoot, envPath)} using 2 of the ${count} funded accounts\n`,
    );
}

function stop() {
    const removed = dockerQuiet(['rm', '-f', config.container]).trim();
    process.stdout.write(
        removed ? `removed ${config.container}\n` : `${config.container} was not running\n`,
    );
}

const command = process.argv[2];
try {
    if (command === 'start') await start();
    else if (command === 'stop') stop();
    else if (command === 'env') await env();
    else {
        process.stderr.write('usage: node scripts/testnode.mjs start|stop|env\n');
        process.exit(2);
    }
} catch (err) {
    process.stderr.write(`${err.message}\n`);
    process.exit(1);
}
